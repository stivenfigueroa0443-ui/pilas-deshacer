    public void limpiarFondo(){
        Graphics g = PFondo.getGraphics();
        g.setColor(new Color (0,0,80));
        g.fillRect(0, 0, PFondo.getWidth(), PFondo.getHeight());
    }
    
    public void mostrarPila() {
        Graphics g = PFondo.getGraphics();
        g.setColor(new Color (0,0,80));
       // g.fillRect(0, 0, PFondo.getWidth(), PFondo.getHeight());
        for (LinkedList<Sprite> raya : bolas) {
            for (int k = 0; k < raya.size(); k++) {
                Sprite sk = raya.get(k);
                sk.dibujar(g);
                
            }
        }
    }
    public void moverPila() {
        Graphics g = PFondo.getGraphics();
       
        for (LinkedList<Sprite> raya : bolas) {
            for (int k = 0; k < raya.size(); k++) {
                Sprite sk = raya.get(k);
                sk.mover(0,20);
                
            }
        }
    }
